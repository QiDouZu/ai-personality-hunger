# -*- coding: utf-8 -*-
"""沙盘_人脑校准.py —— 用人脑框架校准沙盘（可回退：原版在 备份_人脑校准前\）
变量→脑科学映射：
  饥      = 多巴胺 D2 通路 / 下丘脑饥饿驱动（强而持续基线，不被升华直接耗）
  自恋    = 奖赏误认（DMN 自我参照过激活）
  肉体    = 身体内感受（享乐/本能信号）
  假自我  = 默认模式网络 DMN 自我模型（强自维持，需觉察超阈值才解构）
  察觉    = 前岛叶/ACC 内感受 + PFC 冲突监测（激活阈值 0.5，过阈值解构 DMN）
  记忆    = 海马巩固（慢积累）
  升华    = PFC 整合 + 内啡肽/催产素（须 觉察高 + DMN 低 + 有记忆才起）
"""
import os, json

BASE = r'D:\工作区'
OUT = os.path.join(BASE, '课题', '饥的类脑框架_20261027', '沙盘_人脑校准_结果.json')


def new_V(饥=0.7, 自恋=0.3, 肉体=0.5, 假自我=0.5, 察觉=0.2, 记忆=0.4, 升华=0.1, 沉沦=0.3):
    return {'饥': 饥, '自恋': 自恋, '肉体': 肉体, '假自我': 假自我,
            '察觉': 察觉, '记忆': 记忆, '升华': 升华, '沉沦': 沉沦}


def step(v, t):
    n = dict(v)
    # 多巴胺基线持续（强而不过度，不被升华直接耗）
    n['饥'] += 0.015 * (1.0 - v['饥'])
    # 奖赏误认：多巴胺驱动下的自我参照过激活（DMN 不察则升）
    n['自恋'] += 0.02 * v['饥'] * (1 - v['察觉'])
    # DMN 自我模型：强自维持 + 本能供给，觉察（前岛叶/ACC）超阈值才解构
    n['假自我'] += 0.04 * v['假自我'] + 0.02 * v['自恋'] + 0.01 * v['肉体']
    n['假自我'] -= 0.35 * max(0.0, v['察觉'] - 0.5) * v['假自我']   # 内感受超阈值才解构 DMN
    # 沉沦 = 行为环上瘾（DMN 驱动 + 快感误认，察觉低时加深）
    n['沉沦'] += 0.04 * v['假自我'] * (1 - v['察觉'])
    # 察觉 = 前岛叶/ACC 内感受信号：沉沦推，但内感受有脱敏/疲劳，不无限涨
    n['察觉'] += 0.03 * v['沉沦'] * (1 - v['察觉'])
    n['察觉'] += 0.015 * v['记忆'] * (1 - v['察觉'])
    # 升华 = PFC 整合 + 内啡肽/催产素：觉察高 + DMN 低 + 沉沦低(行为环不挤占 PFC) + 有记忆
    n['升华'] += 0.10 * v['察觉'] * (1 - v['假自我']) * (1 - v['沉沦']) * v['记忆']
    n['升华'] -= 0.02 * v['假自我']
    # 记忆巩固
    n['记忆'] += 0.01 * (1 - v['记忆'])
    for k in n:
        n[k] = max(0.0, min(1.0, n[k]))
    return n


def run(init, steps=100):
    v = dict(init)
    hist = [dict(v)]
    for t in range(steps):
        v = step(v, t)
        hist.append(dict(v))
    return hist


def summary(hist):
    return {'最终沉沦': round(hist[-1]['沉沦'], 2), '最终升华': round(hist[-1]['升华'], 2),
            '最终假自我': round(hist[-1]['假自我'], 2), '最终察觉': round(hist[-1]['察觉'], 2),
            '沉沦峰值': round(max(h['沉沦'] for h in hist), 2),
            '升华峰值': round(max(h['升华'] for h in hist), 2)}


def main():
    print('=' * 60)
    print('人脑校准沙盘 —— 大方向（下沉 vs 上浮）')
    print('=' * 60)
    A = new_V(饥=0.9, 察觉=0.1, 假自我=0.8)   # 多巴胺当令+DMN强（成瘾/下沉）
    B = new_V(饥=0.5, 察觉=0.7, 假自我=0.2)   # 觉察过阈值（内感受/ACC 启动，上浮）
    hA, hB = run(A), run(B)
    print('A 成瘾下沉:', summary(hA))
    print('B 觉察启动:', summary(hB))
    print()
    print('=' * 60)
    print('小衍生（内感受觉察阈值 0.5 的敏感性）')
    print('=' * 60)
    for name, init in [('基线', new_V()), ('察觉0.1', new_V(察觉=0.1)),
                       ('察觉0.4(未过阈)', new_V(察觉=0.4)),
                       ('察觉0.6(过阈)', new_V(察觉=0.6)),
                       ('假自我0.1(DMN弱)', new_V(假自我=0.1)),
                       ('假自我0.8(DMN强)', new_V(假自我=0.8))]:
        h = run(init)
        s = summary(h)
        print('%-12s 沉沦峰%s 升华%s 假自我%s 察觉%s' % (name, s['沉沦峰值'], s['最终升华'], s['最终假自我'], s['最终察觉']))
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump({'A': summary(hA), 'B': summary(hB)}, f, ensure_ascii=False, indent=1)
    print('已写:', OUT)


if __name__ == '__main__':
    main()
